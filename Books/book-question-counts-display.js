/* ExamFusion automatic book question-count display.
   Data is generated by tools/update-book-question-counts.py. No API/AI used.
   The counter is intentionally layout-neutral and re-applies after browser back/forward. */
(function () {
  "use strict";

  var current = document.currentScript;
  if (!current || !current.src) return;

  var manifestUrl = new URL("question-counts.json", current.src).href;
  var lastManifest = null;
  var refreshTimer = null;

  function normalizePath(url) {
    try {
      var u = new URL(url, window.location.href);
      if (u.origin !== window.location.origin) return null;

      var p = decodeURIComponent(u.pathname || "");
      // Works on both the custom domain (/Books/...) and github.io/Quiz/Books/...
      var booksAt = p.indexOf("/Books/");
      if (booksAt >= 0) p = p.slice(booksAt + 1);
      else p = p.replace(/^\/+/, "");
      return p;
    } catch (_) {
      return null;
    }
  }

  function formatCount(n) {
    return Number(n).toLocaleString("en-IN") + " Questions";
  }

  function addStyles() {
    if (document.getElementById("efBookQuestionCountStyles")) return;
    var style = document.createElement("style");
    style.id = "efBookQuestionCountStyles";
    style.textContent = [
      ".ef-qcount-badge{display:block!important;width:max-content;max-width:100%;margin-top:4px!important;padding:0!important;border:0!important;background:none!important;box-shadow:none!important;position:static!important;transform:none!important;white-space:nowrap;font-size:10px!important;font-weight:700!important;line-height:1.25!important;letter-spacing:.15px!important;color:currentColor!important;opacity:.72!important;pointer-events:none!important}",
      ".bilabel>.ef-qcount-badge,.link-text>.ef-qcount-badge{flex:0 0 auto!important}",
      "@media(max-width:480px){.ef-qcount-badge{font-size:9px!important;margin-top:3px!important}}"
    ].join("");
    document.head.appendChild(style);
  }

  function applyCounts(manifest) {
    var pages = (manifest && manifest.pages) || {};
    addStyles();

    document.querySelectorAll("a[href]").forEach(function (a) {
      var key = normalizePath(a.getAttribute("href"));
      var existing = a.querySelector(".ef-qcount-badge");

      if (!key || !Object.prototype.hasOwnProperty.call(pages, key)) {
        if (existing) existing.remove();
        return;
      }

      var count = Number(pages[key]);
      if (!Number.isFinite(count) || count <= 0) {
        if (existing) existing.remove();
        return;
      }

      // Put the count inside the text column instead of reserving horizontal space.
      // This keeps desktop/mobile button layouts exactly as designed.
      var holder = a.querySelector(".bilabel") || a.querySelector(".link-text");
      if (!holder) return;

      // A page's own pageshow handler may rebuild its label after browser Back.
      // If that happened, existing is gone and we simply recreate it.
      existing = a.querySelector(".ef-qcount-badge");
      if (!existing) {
        existing = document.createElement("span");
        existing.className = "ef-qcount-badge";
        holder.appendChild(existing);
      } else if (existing.parentNode !== holder) {
        holder.appendChild(existing);
      }

      existing.textContent = formatCount(count);
      existing.title = count.toLocaleString("en-IN") + " Questions";
      existing.setAttribute("aria-label", count.toLocaleString("en-IN") + " questions");
    });
  }

  function loadManifest() {
    // Cache-busting query avoids stale JSON after a GitHub Pages deploy.
    var sep = manifestUrl.indexOf("?") >= 0 ? "&" : "?";
    fetch(manifestUrl + sep + "v=" + Date.now(), { cache: "no-store" })
      .then(function (r) {
        if (!r.ok) throw new Error("question-count manifest unavailable");
        return r.json();
      })
      .then(function (manifest) {
        lastManifest = manifest;
        applyCounts(manifest);
      })
      .catch(function () {
        // Counts are enhancement-only; navigation must remain fully usable.
      });
  }

  function reapplyAfterNavigation() {
    clearTimeout(refreshTimer);
    // Run after the page's own pageshow restoration code has rebuilt labels.
    refreshTimer = setTimeout(function () {
      if (lastManifest) applyCounts(lastManifest);
      // Also refresh JSON so a recently deployed count is not stale.
      loadManifest();
    }, 25);
  }

  // Defer scripts execute after HTML parsing, so this is safe immediately.
  loadManifest();
  window.addEventListener("pageshow", reapplyAfterNavigation);
})();
