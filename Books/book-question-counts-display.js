/* ExamFusion automatic book question-count display.
   Data is generated by tools/update-book-question-counts.py. No API/AI used. */
(function () {
  "use strict";

  var current = document.currentScript;
  if (!current || !current.src) return;
  var manifestUrl = new URL("question-counts.json", current.src).href;

  function normalizePath(url) {
    try {
      var u = new URL(url, window.location.href);
      if (u.origin !== window.location.origin) return null;
      var p = decodeURIComponent(u.pathname).replace(/^\/+/, "");
      return p;
    } catch (_) {
      return null;
    }
  }

  function formatCount(n) {
    return Number(n).toLocaleString("en-IN") + " Q";
  }

  function addStyles() {
    if (document.getElementById("efBookQuestionCountStyles")) return;
    var style = document.createElement("style");
    style.id = "efBookQuestionCountStyles";
    style.textContent = [
      ".ef-qcount-link{position:relative!important;padding-right:92px!important}",
      ".ef-qcount-link.ef-qcount-with-chevron{padding-right:118px!important}",
      ".ef-qcount-badge{position:absolute;right:14px;top:50%;transform:translateY(-50%);display:inline-flex;align-items:center;justify-content:center;min-width:56px;max-width:78px;padding:5px 8px;border-radius:999px;font-size:11px!important;font-weight:800!important;line-height:1!important;letter-spacing:.15px;white-space:nowrap;color:#fff7df;background:rgba(8,12,24,.48);border:1px solid rgba(255,224,148,.34);box-shadow:0 4px 14px rgba(0,0,0,.18);z-index:3;pointer-events:none}",
      ".ef-qcount-with-chevron .ef-qcount-badge{right:42px}",
      "@media(max-width:480px){.ef-qcount-link{padding-right:82px!important}.ef-qcount-link.ef-qcount-with-chevron{padding-right:106px!important}.ef-qcount-badge{right:10px;min-width:50px;padding:5px 6px;font-size:10px!important}.ef-qcount-with-chevron .ef-qcount-badge{right:36px}}"
    ].join("");
    document.head.appendChild(style);
  }

  function applyCounts(manifest) {
    var pages = (manifest && manifest.pages) || {};
    addStyles();
    document.querySelectorAll("a[href]").forEach(function (a) {
      if (a.querySelector(":scope > .ef-qcount-badge")) return;
      var key = normalizePath(a.getAttribute("href"));
      if (!key || !Object.prototype.hasOwnProperty.call(pages, key)) return;
      var count = Number(pages[key]);
      if (!Number.isFinite(count) || count <= 0) return;

      a.classList.add("ef-qcount-link");
      if (a.querySelector(".chevron-icon")) a.classList.add("ef-qcount-with-chevron");
      var badge = document.createElement("span");
      badge.className = "ef-qcount-badge";
      badge.textContent = formatCount(count);
      badge.title = count.toLocaleString("en-IN") + " Questions";
      badge.setAttribute("aria-label", count.toLocaleString("en-IN") + " questions");
      a.appendChild(badge);
    });
  }

  fetch(manifestUrl, { cache: "no-store" })
    .then(function (r) {
      if (!r.ok) throw new Error("question-count manifest unavailable");
      return r.json();
    })
    .then(applyCounts)
    .catch(function () {
      // Counts are enhancement-only; navigation must remain fully usable if unavailable.
    });
})();
