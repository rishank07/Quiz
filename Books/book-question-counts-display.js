/* ExamFusion automatic section-count display.
   Data is generated by tools/update-book-question-counts.py. No API/AI used.
   Counts are layout-neutral and re-apply after browser back/forward. */
(function () {
  "use strict";

  var current = document.currentScript;
  if (!current || !current.src) return;

  var scriptUrl = new URL(current.src, window.location.href);
  var manifestUrl = new URL("question-counts.json", scriptUrl).href;
  // Script lives at <site-root>/Books/book-question-counts-display.js.
  // Going one directory up from /Books/ gives the correct site root on both
  // custom domains (/) and GitHub Pages project URLs (/Quiz/).
  var siteRootPath = decodeURIComponent(new URL("../", scriptUrl).pathname);
  var lastManifest = null;
  var refreshTimer = null;

  function normalizePath(url) {
    try {
      var u = new URL(url, window.location.href);
      if (u.origin !== window.location.origin) return null;
      var p = decodeURIComponent(u.pathname || "");
      if (p.indexOf(siteRootPath) === 0) p = p.slice(siteRootPath.length);
      else p = p.replace(/^\/+/, "");
      return p.replace(/^\/+/, "");
    } catch (_) {
      return null;
    }
  }

  function isLandingPage() {
    var p = decodeURIComponent(window.location.pathname || "");
    if (p.indexOf(siteRootPath) === 0) p = p.slice(siteRootPath.length);
    p = p.replace(/^\/+|\/+$/g, "");
    return p === "" || /^index\.html?$/i.test(p);
  }

  function pluralUnit(unit, count) {
    if (unit === "Maps") return count === 1 ? "Map" : "Maps";
    if (unit === "Facts") return count === 1 ? "Fact" : "Facts";
    if (unit === "Entries") return count === 1 ? "Entry" : "Entries";
    return count === 1 ? "Question" : "Questions";
  }

  function formatCount(n, unit, compact) {
    var formatted = Number(n).toLocaleString("en-IN");
    if (compact) {
      if (unit === "Questions") return formatted + " Q";
      if (unit === "Maps") return formatted + " Maps";
      if (unit === "Facts") return formatted + " Facts";
      if (unit === "Entries") return formatted + " Entries";
    }
    return formatted + " " + pluralUnit(unit, Number(n));
  }

  function addStyles() {
    if (document.getElementById("efBookQuestionCountStyles")) return;
    var style = document.createElement("style");
    style.id = "efBookQuestionCountStyles";
    style.textContent = [
      ".ef-qcount-badge{display:block!important;width:max-content;max-width:100%;margin-top:5px!important;padding:0!important;border:0!important;background:none!important;box-shadow:none!important;position:static!important;transform:none!important;white-space:nowrap;font-size:14px!important;font-weight:850!important;line-height:1.25!important;letter-spacing:.2px!important;color:#fff2b8!important;opacity:1!important;text-shadow:0 0 9px rgba(255,218,112,.62),0 1px 2px rgba(0,0,0,.45)!important;pointer-events:none!important}",
      ".bilabel>.ef-qcount-badge,.link-text>.ef-qcount-badge{flex:0 0 auto!important}",
      "body.ef-qcount-landing .ef-qcount-badge{font-size:10px!important;font-weight:750!important;margin-top:4px!important;color:currentColor!important;opacity:.78!important;text-shadow:none!important;letter-spacing:.15px!important}",
      "body.ef-qcount-landing .menu>li>a{min-height:82px!important}",
      ".ef-qcount-placeholder{display:block!important;visibility:hidden!important;height:12px!important;margin-top:4px!important;font-size:10px!important;line-height:1.2!important;pointer-events:none!important}",
      "@media(max-width:480px){.ef-qcount-badge{font-size:13px!important;margin-top:4px!important}body.ef-qcount-landing .ef-qcount-badge{font-size:9px!important;margin-top:3px!important}body.ef-qcount-landing .menu>li>a{min-height:78px!important}}"
    ].join("");
    document.head.appendChild(style);
  }

  function bestHolder(a) {
    return a.querySelector(".bilabel") ||
      a.querySelector(".link-text") ||
      a.querySelector(".text") ||
      a.querySelector(".label") ||
      a.querySelector(".title") ||
      null;
  }

  function applyCounts(manifest) {
    var pages = (manifest && manifest.pages) || {};
    var units = (manifest && manifest.units) || {};
    var landing = isLandingPage();
    addStyles();
    if (document.body) document.body.classList.toggle("ef-qcount-landing", landing);

    document.querySelectorAll("a[href]").forEach(function (a) {
      var key = normalizePath(a.getAttribute("href"));
      var existing = a.querySelector(".ef-qcount-badge");

      if (!key || !Object.prototype.hasOwnProperty.call(pages, key)) {
        if (existing) existing.remove();
        return;
      }

      var count = Number(pages[key]);
      if (!Number.isFinite(count) || count <= 0) {
        if (existing) existing.remove();
        return;
      }

      var holder = bestHolder(a);
      if (!holder) return;

      existing = a.querySelector(".ef-qcount-badge");
      if (!existing) {
        existing = document.createElement("span");
        existing.className = "ef-qcount-badge";
        holder.appendChild(existing);
      } else if (existing.parentNode !== holder) {
        holder.appendChild(existing);
      }

      var unit = units[key] || "Questions";
      existing.textContent = formatCount(count, unit, landing);
      existing.title = formatCount(count, unit, false);
      existing.setAttribute("aria-label", formatCount(count, unit, false));
    });

    // Maths Speed Booster intentionally has no count. Reserve one invisible
    // count line on the landing page so its button height matches the other
    // counted section buttons without showing any number.
    document.querySelectorAll("a[href]").forEach(function (a) {
      var key = normalizePath(a.getAttribute("href"));
      var ph = a.querySelector(".ef-qcount-placeholder");
      var isMaths = key === "Maths Speed Booster/math-speed-booster.html";
      if (!landing || !isMaths) {
        if (ph) ph.remove();
        return;
      }
      var holder = bestHolder(a);
      if (!holder) return;
      if (!ph) {
        ph = document.createElement("span");
        ph.className = "ef-qcount-placeholder";
        ph.textContent = "placeholder";
        holder.appendChild(ph);
      }
    });
  }

  // Some existing hub pages temporarily replace link text/HTML with a
  // "Loading..." label before navigation.  If our count badge is inside that
  // markup, browser Back/Forward can otherwise restore the count as plain text
  // and then append another badge (or lose the structured holder entirely).
  // Preserve the original link markup *without* generated count elements and
  // restore it on pageshow before re-applying the current count.
  function cleanBaseHtml(a) {
    var clone = a.cloneNode(true);
    clone.querySelectorAll(".ef-qcount-badge,.ef-qcount-placeholder").forEach(function (n) {
      n.remove();
    });
    return clone.innerHTML;
  }

  function rememberNavigationMarkup(event) {
    if (event.button !== 0 || event.ctrlKey || event.metaKey || event.shiftKey || event.altKey) return;
    var target = event.target;
    if (!target || !target.closest) return;
    var a = target.closest("a[href]");
    if (!a || (a.target && a.target.toLowerCase() === "_blank")) return;

    var decorations = a.querySelectorAll(".ef-qcount-badge,.ef-qcount-placeholder");
    if (!decorations.length) return;

    // Save a pristine copy each time, excluding our generated decorations.
    a.dataset.efQcountRestoreHtml = cleanBaseHtml(a);

    // Remove generated decorations before the page's legacy onclick handler
    // reads innerText/innerHTML. This prevents counts being baked into its
    // own "original" text snapshot.
    decorations.forEach(function (n) {
      n.remove();
    });
  }

  function restoreNavigationMarkup() {
    document.querySelectorAll("a[data-ef-qcount-restore-html]").forEach(function (a) {
      var html = a.dataset.efQcountRestoreHtml;
      if (html) a.innerHTML = html;
      delete a.dataset.efQcountRestoreHtml;
    });
  }

  function loadManifest() {
    var sep = manifestUrl.indexOf("?") >= 0 ? "&" : "?";
    fetch(manifestUrl + sep + "v=" + Date.now(), { cache: "no-store" })
      .then(function (r) {
        if (!r.ok) throw new Error("question-count manifest unavailable");
        return r.json();
      })
      .then(function (manifest) {
        lastManifest = manifest;
        applyCounts(manifest);
      })
      .catch(function () {
        // Counts are enhancement-only; navigation must remain fully usable.
      });
  }

  function reapplyAfterNavigation() {
    restoreNavigationMarkup();
    clearTimeout(refreshTimer);
    refreshTimer = setTimeout(function () {
      if (lastManifest) applyCounts(lastManifest);
      loadManifest();
    }, 25);
  }

  // Capture runs before inline onclick handlers used by the existing hubs.
  document.addEventListener("click", rememberNavigationMarkup, true);
  loadManifest();
  window.addEventListener("pageshow", reapplyAfterNavigation);
})();
