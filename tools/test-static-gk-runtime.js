#!/usr/bin/env node
// Usage: EFP_TEST_JSDOM=/path/to/jsdom node tools/test-static-gk-runtime.js
const {JSDOM} = require(process.env.EFP_TEST_JSDOM || 'jsdom');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const read = f => fs.readFileSync(path.join(root,f),'utf8');
function make(file, search='', storage={}) {
  const dom = new JSDOM(read(file), {url:'https://examfusionprep.com/' + file.replaceAll(' ','%20') + search,runScripts:'outside-only',pretendToBeVisual:true});
  const w = dom.window, ctx = dom.getInternalVMContext();
  w.scrollTo=()=>{};w.HTMLElement.prototype.scrollIntoView=()=>{};w.confirm=()=>true;w.alert=()=>{};
  Object.entries(storage).forEach(([k,v])=>w.localStorage.setItem(k,v));
  w.fetch=async url=>({ok:true,text:async()=>read('Original Practice/' + String(url).replace(/^\.\//,''))});
  const run=code=>vm.runInContext(code,ctx);
  return {dom,w,run,inline(instrument=s=>s){Array.from(w.document.scripts).forEach(s=>{if(!s.src&&!/json/.test(s.type))run(instrument(s.textContent))})}};
}
const snapshot = w => Object.fromEntries(Array.from({length:w.localStorage.length},(_,i)=>{const k=w.localStorage.key(i);return[k,w.localStorage.getItem(k)]}));
function staticPage(search='',storage={}) {const p=make('Original Practice/Static_GK_Complete_Practice.html',search,storage);p.run(read('black-mode.js'));p.inline();p.run(read('search-logic.js'));p.run(read('Original Practice/original-practice.js'));return p}
async function main(){
  let p=staticPage(), w=p.w;
  assert.equal(w.document.querySelectorAll('[onclick^="goToQuiz"]').length,20);
  assert(w.document.querySelector('.efp-op-progress').textContent.includes('0 / 20'));
  assert(w.document.querySelector('.efp-op-search input'));
  p.run("goToQuiz(Object.keys(MASTER['Static GK'])[0])");
  p.run('selectOption(0,state.shuffleMap["0-0"].indexOf(currentAnswerIndex(state.quizData[0].questions[0])))');
  assert.equal(p.run('state.score.correct'),1);
  assert(!w.document.querySelector('#exp-0').classList.contains('hidden'));
  p.run('switchSection(1);switchSection(0)');
  assert.equal(w.document.querySelectorAll('#opts-0 .answered').length,4);
  assert.equal(p.run('state.score.attempted'),1);
  w.document.querySelector('#q-0 .efp-op-star').click();
  const bookmarks=JSON.parse(w.localStorage.getItem('efp_bookmarks'));
  assert(Object.keys(bookmarks).some(k=>k.includes('#op|staticgk|')));
  assert.equal(JSON.parse(w.localStorage.getItem('efp_visited_originalpractice_staticgk')).length,1);
  w.document.querySelector('.efp-op-bookmarkbar button').click();
  assert.equal(w.document.querySelectorAll('#questions-container > .efp-op-qcard:not(.efp-op-bookmark-hidden)').length,1);
  w.document.querySelector('.efp-op-bookmarkbar button').click();
  const saved=snapshot(w), reloadUrl=w.location.search;
  p.run("goToChapters('Static GK')");
  assert.equal(p.run('state.score.attempted'),0);
  w.document.querySelector('.efp-op-progress-reset').click();
  assert.equal(w.localStorage.getItem('efp_visited_originalpractice_staticgk'),null);
  assert.equal(Object.keys(JSON.parse(w.localStorage.getItem('efp_bookmarks'))).length,1);
  p.dom.window.close();
  p=staticPage(reloadUrl,saved);w=p.w;
  assert.equal(p.run('state.screen'),'quiz');assert.equal(p.run('state.score.attempted'),0);
  assert(w.document.querySelector('#q-0 .efp-op-star').classList.contains('is-bookmarked'));
  p.run('selectOption(0,0)');
  w.dispatchEvent(new w.PageTransitionEvent('pageshow',{persisted:true}));
  assert.equal(p.run('state.score.attempted'),0);
  assert.equal(w.document.querySelectorAll('.option-btn.answered').length,0);
  p.run('toggleBlackMode()');assert.equal(w.localStorage.getItem('efp_black_mode'),'on');
  w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
  assert(w.document.documentElement.classList.contains('efp-black-invert') || w.document.documentElement.classList.contains('efp-black'));
  p.dom.window.close();
  const idx=make('Original Practice/index.html','',saved);
  idx.run(read('Original Practice/original-practice-index.js'));idx.inline();
  assert(idx.w.document.querySelector('[data-progress-key="efp_visited_originalpractice_staticgk"] .progress-copy').textContent.includes('1 / 20'));
  const input=idx.w.document.getElementById('chapterSearch');input.value='भारत में प्रथम';input.dispatchEvent(new idx.w.Event('input'));
  assert(idx.w.document.querySelector('#results a[href*="Static_GK"]'));
  idx.dom.window.close();
  const m=make('Original Practice/Mixed_Practice.html');
  m.inline(s=>s.includes('var POOLS=')?s.replace(/\}\)\(\);\s*$/, 'window.__test={buildPool:buildPool,generateSet:generateSet,getQuestions:function(){return currentQuestions}};})();'):s);
  assert.equal(m.w.document.querySelectorAll('#majorPools input').length,8);
  const pool=await m.w.__test.buildPool('staticgk');assert.equal(pool.length,2642);
  assert.equal(new Set(pool.map(q=>q.id)).size,2642);
  await m.w.__test.generateSet(['staticgk','english'],20);
  const mixed=m.w.__test.getQuestions();assert.equal(mixed.length,20);
  assert.equal(mixed.filter(q=>q.poolKey==='staticgk').length,10);
  assert.equal(mixed.filter(q=>q.poolKey==='english').length,10);
  assert.equal(new Set(mixed.map(q=>q.id)).size,20);
  m.w.document.getElementById('bookmarkBtn').click();
  m.w.document.querySelector('#options input').click();m.w.document.getElementById('checkBtn').click();
  assert.equal(m.w.document.getElementById('statAttempted').textContent,'1');
  m.w.document.getElementById('nextBtn').click();m.w.document.getElementById('prevBtn').click();
  assert(m.w.document.getElementById('answerBox').classList.contains('show'));
  assert.equal(Object.keys(JSON.parse(m.w.localStorage.getItem('efp_mixed_practice_state_v1')).answers).length,0);
  const mixSaved=snapshot(m.w);m.dom.window.close();
  const b=make('backup-restore.html','',{...saved,...mixSaved});
  b.inline(s=>s.includes('function backupPayload')?s.replace(/\}\)\(\);\s*$/, 'window.__backup={payload:backupPayload};})();'):s);
  const payload=b.w.__backup.payload();
  assert.equal(payload.data.progress.efp_visited_originalpractice_staticgk.length,1);
  assert(Object.keys(payload.data.bookmarks).some(k=>k.includes('#op|staticgk|')));
  assert.equal(payload.data.practice.mixedState.selectedKeys[0],'staticgk');
  assert.equal(payload.data.practice.mixedBookmarks.length,1);
  b.dom.window.close();
  console.log('PASS: actual DOM chapter dashboard, counts, answers/section navigation, chapter reset, refresh/back reset, bookmarks/filter, shared dark mode, index Hindi search/progress, 10+10 Static GK/English mixed test, mixed bookmarks/reset and backup payload.');
}
main().catch(e=>{console.error(e);process.exit(1)});
